# ── Singleton ────────────────────────────────────────────────────────────────

_heartbeat_instance: HeartbeatEngine | None = None
_heartbeat_lock = threading.Lock()


def get_heartbeat() -> HeartbeatEngine:
    """Get the global heartbeat engine singleton."""
    global _heartbeat_instance
    with _heartbeat_lock:
        if _heartbeat_instance is None:
            _heartbeat_instance = HeartbeatEngine()
        return _heartbeat_instance


