def tool_get_heartbeat_status() -> str:
    """Execute get_heartbeat_status tool."""
    hb = get_heartbeat()
    return json.dumps(hb.get_status(), indent=2)


def tool_get_pending_alerts() -> str:
    """Execute get_pending_alerts tool."""
    hb = get_heartbeat()
    critical = hb.event_bus.get_pending(AlertUrgency.CRITICAL, mark_handled=False)
    important = hb.event_bus.get_pending(AlertUrgency.IMPORTANT, mark_handled=False)
    alerts = [e.to_dict() for e in (critical + important)]
    return json.dumps(alerts, indent=2)


